// Sprache des Handys als Startwert, sonst Deutsch.
export function deviceLanguage() {
  try {
    const code = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2);
    return LANGUAGES[code] ? code : 'de';
  } catch {
    return 'de';
  }
}
